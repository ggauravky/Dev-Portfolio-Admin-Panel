const { test } = require("node:test");
const assert = require("node:assert/strict");
const { createApp } = require("../app");
const { createDatabases } = require("../config/database");
const { http, login } = require("./auth-fixture");
const { chatFixture, now, uid, sessionId, firstSource } = require("./chat-fixture");

test("AI endpoints aggregate and paginate real isolated MongoDB data without exposing bindings", {
  skip: process.env.RUN_ADMIN_MONGO_TEST !== "1", timeout: 30_000,
}, async (t) => {
  const fixture = await chatFixture();
  t.after(() => fixture.client.close());
  const db = createDatabases(fixture.config);
  t.after(() => db.close());
  const request = await http(t, createApp({ config: fixture.config, db, chatNow: now, log: () => {} }));
  const auth = await login(request);
  assert.equal(auth.response.status, 200);
  const get = async (path, status = 200) => {
    const response = await request(path, { cookie: auth.cookie });
    assert.equal(response.status, status, path);
    assert.equal(response.headers.get("cache-control"), "no-store");
    assert.ok(response.headers.get("x-request-id"));
    const data = await response.json();
    assert.doesNotMatch(JSON.stringify(data), /"owner"|"ipHash"|"sessionId"|private-fixture-ip|exclude-this-field|internal-visitor-key|never-return-this|private-fixture-lock/);
    return data.data ?? data;
  };
  assert.equal((await get("/chats/" + uid(1)))._id, uid(1));
  assert.equal((await get("/chats/" + uid(1))).sources[0].title, firstSource.title);
  assert.equal((await get("/chats/" + uid(4))).provider, "historical-provider");
  assert.equal((await get("/chats/" + uid(4))).sources[0].mapping, "unavailable");
  await get("/chats/invalid-id", 400);
  await get("/chat-conversations/invalid-id", 400);
  await get("/chats/" + uid(900), 404);
  await get("/chats?pageSize=101", 400);
  await get("/chats?range=custom&from=2026-11-25&to=2026-11-23", 400);
  assert.equal((await get("/chats?search=%5Bliteral%5D")).total, 1);
  assert.equal((await get("/chats?provider=groq&cached=true&matched=true&retrieval=cache")).items[0]._id, uid(2));
  assert.equal((await get("/chats?provider=unknown")).items[0]._id, uid(4));
  assert.equal((await get("/chats?conversation=" + uid(1))).total, 2);
  await get("/chats?conversation=" + sessionId, 404);
  const groups = await get("/chat-conversations?pageSize=2&page=1");
  assert.equal(groups.total, 5);
  assert.equal(groups.items.length, 2);
  const lastGroups = await get("/chat-conversations?pageSize=2&page=3");
  assert.equal(lastGroups.items[0].reference, uid(1));
  assert.equal(lastGroups.items[0].turns, 2);
  const detail = await get("/chat-conversations/" + uid(1));
  assert.deepEqual(detail.items.map((row) => row._id), [uid(1), uid(2)]);
  assert.equal((await get("/chat-conversations/" + uid(3))).total, 1);
  assert.equal((await get("/chat-conversations/" + uid(4))).total, 1);

  const report = await get("/chat-analytics?range=7d");
  const core = report.core.data;
  assert.equal(core.turns, 6);
  assert.equal(core.conversations, 5);
  assert.deepEqual(core.daily.map((row) => [row.day, row.turns, row.conversations]), [["2026-11-24", 1, 1], ["2026-11-25", 5, 5]]);
  assert.deepEqual(core.cache, { hits: 1, misses: 4, rate: 0.2 });
  assert.deepEqual(core.retrieval, { matched: 3, unmatched: 2, allRate: 0.6, eligibleMatched: 2, eligibleObserved: 3, eligibleRate: 2 / 3 });
  assert.equal(core.aborted.count, 1);
  assert.equal(core.local, 2);
  assert.equal(core.distributions.response.find((item) => item.key === "groq").count, 2);
  assert.equal(core.distributions.response.find((item) => item.key === "unknown").count, 1);
  assert.equal(report.latency.data.count, 4);
  assert.equal(report.latency.data.medianMs, 200);
  assert.equal(report.latency.data.p95Ms, 600);
  const empty = await get("/chat-analytics?from=2026-11-23&to=2026-11-23");
  assert.equal(empty.core.data.turns, 0);
  assert.equal(empty.core.data.cache.rate, null);
  assert.equal(empty.latency.data.medianMs, null);
  const k = await get("/chat-knowledge?sourceType=blog");
  assert.equal(k.chunkCount, 324);
  assert.ok(k.catalog.items.every((item) => item.type === "blog" && !item.vec && !item.text));
  assert.equal(k.observations.versions.length, 2);
  assert.equal(k.observations.retrieved[0].count, 4);
  const ops = await get("/chat-operations");
  assert.equal(ops.quota.data.find((row) => row.label === "groq" && row.metric === "rpm").count, 4);
  assert.equal(ops.quota.data.find((row) => row.label === "gemini" && row.metric === "rpm").count, null);
  assert.equal(ops.cooldowns.data.find((row) => row.label === "groq").status, "active");
  assert.equal(ops.cooldowns.data.find((row) => row.label === "gemini").status, "not_observed");
  assert.equal(ops.cacheEntries.data, 1);
  assert.equal((await request("/chats/" + uid(1), { cookie: auth.cookie, method: "DELETE" })).status, 403);
  assert.equal(await fixture.client.db("portfolio_chat").collection("chat_turns").countDocuments(), 6);
});
